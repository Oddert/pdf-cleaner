def re_process_block_text(
    words: List[Tuple[str, float, float]],
    threshold_distance: float = 2,
    debug: bool = False,
):
    result: List[str] = []
    str_segment = ''
    last_word = None
    force_next_join = False

    for word in words:
        if last_word is None:
            if debug:
                print('last word is None, setting new word')
            last_word = word
            str_segment += word[0]
        else:
            if debug:
                print(
                    'looking at word ',
                    word,
                    '. Distance from last word: ',
                    word[1] - last_word[2],
                )
            if word[0] == '\xad':
                if debug:
                    print('hyphen detected, forcing the next join...')
                force_next_join = True
                
            elif force_next_join:
                if debug:
                    print('...next join actioned, continuing.')
                str_segment += word[0]
                force_next_join = False
                
            elif word[0] == '':
                if debug:
                    print('is whitespace, continuing...')
                
            elif word[1] - last_word[2] <= threshold_distance:
                if debug:
                    print('is part of same segment')
                str_segment += word[0]

            else:
                if debug:
                    print('is the beginning of a new segment')
                result.append(str_segment)
                str_segment = word[0]

            last_word = word

        if debug:
            print('====> ', str_segment)

    result.append(str_segment)
    return result


