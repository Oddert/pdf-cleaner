def filter_whitespace(block: Tuple[str, float, float]) -> bool:
    strp = block[0].strip()
    return strp != '' and strp != '\xad'


def filter_invalid_words(
    words: List[Tuple[str, float, float]],
) -> List[Tuple[str, float, float]]:
    filtered_for_whitespace = filter(filter_whitespace, words)
    return [x for x in filtered_for_whitespace]


